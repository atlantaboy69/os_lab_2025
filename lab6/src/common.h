#ifndef COMMON_H
#define COMMON_H

#include <stdbool.h>
#include <stdint.h>

/*
 * Максимальная длина строки с IP-адресом или доменным именем.
 * 255 байт достаточно для IPv4, IPv6 и стандартных FQDN-имен.
 */
#define MAX_IP_LEN 255

/*
 * Структура для хранения сетевого адреса сервера:
 * ip   - строковое представление IP-адреса или доменного имени
 * port - номер TCP-порта
 */
struct Server {
    char ip[MAX_IP_LEN];
    int port;
};

/*
 * Быстрое модульное умножение методом удвоения (аналог двоичного возведения в степень).
 * Вычисляет (a * b) % mod без переполнения 64-битного целого числа,
 * разбивая операцию на сложения по модулю за O(log b).
 */
uint64_t MultModulo(uint64_t a, uint64_t b, uint64_t mod);

/*
 * Безопасный парсинг беззнакового 64-битного целого числа из строки.
 * Проверяет диапазон, отсутствие посторонних символов и ошибки функции strtoull.
 */
bool ConvertStringToUI64(const char *str, uint64_t *val);

#endif // COMMON_H